package com.leepy0.photocull.analysis

import com.leepy0.photocull.data.settings.BlurSensitivity

/**
 * 흐림 판정 기준값을 한 곳에서 관리한다.
 * 점수 = 긴 변 약 3000px로 축소한 그레이스케일 영상을 6x4 타일로 나눠 구한 Laplacian 분산의 상위 3개 평균.
 *
 * ## 보정 근거
 * Canon EOS R10 실사진 19장(Wikimedia Commons `Category:Taken_with_Canon_EOS_R10`: 건물, 노면전차·기차, 실내, 쇼핑몰,
 * 제품 접사, 새, 해 질 녘·야간 조명). 원본은 요청 제한으로 받지 못해 3840px 썸네일을 원본 화소 기준으로 환산했다:
 * 열화는 원본 화소 단위 파라미터 × 배율로 적용 → 원본 기준 1/2 크기(앱의 inSampleSize=2)로 영역 평균 축소 →
 * 앱과 같은 [Sharpness.compute]. 하네스: test `CalibrationHarnessTest`(PHOTOCULL_CALIB_DIR 지정 시에만 실행).
 * 사진은 저장소에 넣지 않았다. σ·모션 길이는 원본(6000px) 화소 기준, 잡음은 원본에서 σ인 백색 잡음.
 *
 * ```
 * 조건            최소   10%   중앙값   90%    최대   | 후보 수(19장): 낮음40 보통150 높음400
 * 원본             207   506   1263   3592   7837  |                  0     0      1
 * 가우시안 σ1        96   264    433   1424   2781  |                  0     1      8
 * 가우시안 σ2        26    56    101    269    445  |                  1    13     18
 * 가우시안 σ4       3.7   7.1   15.9   24.8   34.3  |                 19    19     19
 * 모션 5px          116   290    512   1546   2906  |                  0     1      5
 * 모션 15px          48   110    235    652    818  |                  0     5     13
 * 잡음 σ8           526   825   1582   3910   8153  |                  0     0      0
 * σ4 + 잡음 σ8      325   327    337    344    354  |                  0     0     19
 * ```
 * - 낮음 40(유지): σ4는 모두 잡고 σ2는 1/19만 — 확실히 흐린 사진만.
 * - 보통 150(기존 80): σ2의 13/19를 잡고 σ1은 1/19, 원본은 0/19(최저 원본 207과 1.4배 여유). 80은 σ2를 6/19만 잡았다.
 * - 높음 400(기존 150): σ1의 8/19, σ2의 18/19. 대가로 디테일이 아주 적은 원본 1/19(벽 앞 올빼미, 207)도 후보가 된다.
 *
 * ## 한계
 * - 장면에 따라 점수가 40배 차이 나므로(원본 207~7837) 절대 임계값만으로 완벽히 나눌 수 없다. 그룹 안 상대 비교가 더 믿을 만하다.
 * - 한 방향 모션 블러는 점수를 1/5 정도만 낮춘다(15px 중앙값 0.21배, σ4는 0.01배): 낮음은 15px 모션을 못 잡는다.
 * - 백색 잡음은 점수를 ≈ 20·σ²(분석 영상 기준 σ)만큼 올려 흐림을 가릴 수 있다(σ4 + 잡음 σ8 → 약 340).
 *   단 실제 야간 사진의 가장 평평한 타일 분산은 7~195(어두운 하늘 7.1 ≈ 분석 기준 σ 0.6)로, 카메라 잡음 제거와
 *   1/2 축소를 거친 실제 JPEG 잡음은 합성 σ8보다 훨씬 작다.
 * - 썸네일 경로라 앱(JPEG DCT 축소)과 절대값이 ±30% 다를 수 있다. 실제 R10 원본으로 하네스를 다시 돌려 확인할 것.
 * - 실험(앱 미적용): 점수 − 최저 타일 분산을 쓰면 σ4+잡음σ8 중앙값 337 → 20, 원본 중앙값 1263 → 1250(최저 207 → 135).
 *   축별 2차 미분 분산의 작은 쪽을 쓰면 모션15 중앙값 235 → 11(원본 1263 → 378). 도입하려면 설계 변경 후 재보정이 필요하다.
 */
object BlurThresholds {
    /** 단독 사진: 점수가 이 값 미만이면 흐림 후보 */
    fun threshold(sensitivity: BlurSensitivity): Double = when (sensitivity) {
        BlurSensitivity.LOW -> 40.0
        BlurSensitivity.NORMAL -> 150.0
        BlurSensitivity.HIGH -> 400.0
    }

    /**
     * 그룹 안: 그룹 최고 점수의 이 비율 미만이면 상대적으로 흐린 사진.
     * 같은 장면이면 σ1 흐림은 원본의 0.40배, 5px 모션은 0.45배(중앙값)로 떨어지므로 0.6이면 이런 컷을 잡고,
     * 같은 장면을 다시 찍은 정상 컷끼리의 작은 차이는 넘긴다. (유지)
     */
    const val GROUP_RELATIVE_RATIO = 0.6
}
